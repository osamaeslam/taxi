ALTER TABLE rides ADD COLUMN final_price INTEGER DEFAULT 0;
ALTER TABLE rides ADD COLUMN negotiation_state TEXT DEFAULT 'open'; -- open | driver_offered | client_countered | agreed | rejected

CREATE TABLE IF NOT EXISTS ride_bids (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  ride_id INTEGER NOT NULL REFERENCES rides(id),
  driver_id INTEGER NOT NULL REFERENCES drivers(id),
  driver_name TEXT NOT NULL,
  driver_phone TEXT NOT NULL,
  driver_car TEXT,
  driver_plate TEXT,
  offered_price INTEGER NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending', -- pending | accepted | rejected | countered
  created_at INTEGER NOT NULL DEFAULT (strftime('%s', 'now'))
);

